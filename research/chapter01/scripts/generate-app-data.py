#!/usr/bin/env python3
"""
Australia Clarity — Chapter 01 data transformation (research pipeline).

Reads the verified series CSVs in research/chapter01/series/ (extracted from
ABS time-series spreadsheets and the World Bank API; see
research/chapter01/series/README.md and abs-nstp-extraction-notes.md) and
emits a typed TypeScript data module consumed by the chapter's chart
definitions.

Reproducibility: run from the repository root:
    python3 research/chapter01/scripts/generate-app-data.py

Every figure in the output is traceable to a cited source; no values are
invented or estimated here — only formatting/reshaping.
"""

import csv
import os

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SERIES = os.path.join(BASE, "series")
OUT = os.path.normpath(
    os.path.join(
        BASE, "..", "..", "src", "chapters", "chapter-01", "data", "generated.ts"
    )
)

MONTHS = {
    "03": "Mar", "06": "Jun", "09": "Sep", "12": "Dec",
}

STATE_SHORT = {
    "New South Wales": "NSW",
    "Victoria": "Vic.",
    "Queensland": "Qld",
    "South Australia": "SA",
    "Western Australia": "WA",
    "Tasmania": "Tas.",
    "Northern Territory": "NT",
    "Australian Capital Territory": "ACT",
}


def read_csv(name):
    with open(os.path.join(SERIES, name), newline="", encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def quarter_label(q):
    year, month = q.split("-")
    return f"{MONTHS[month]} {year}"


def points(rows, x_key, y_key, x_transform=None):
    out = []
    for row in rows:
        raw = row[y_key]
        if raw is None or raw.strip() == "":
            continue
        x = row[x_key]
        if x_transform:
            x = x_transform(x)
        out.append({"x": x, "y": float(raw)})
    return out


def main():
    # 1. ERP at 30 June, annual (ABS)
    erp_rows = read_csv("abs-erp-annual.csv")
    erp_annual = points(erp_rows, "year", "erp_thousands")

    # 2. Components of change, quarterly (ABS)
    comp_rows = read_csv("abs-components-quarterly.csv")
    births = points(comp_rows, "quarter", "births", quarter_label)
    deaths = points(comp_rows, "quarter", "deaths", quarter_label)
    natural_increase = points(comp_rows, "quarter", "natural_increase", quarter_label)
    nom = points(comp_rows, "quarter", "net_overseas_migration", quarter_label)

    # 3. Population by state/territory, latest (ABS)
    state_rows = read_csv("abs-states-latest.csv")
    states = [
        {"x": STATE_SHORT.get(row["state_territory"], row["state_territory"]),
         "y": int(row["population"])}
        for row in state_rows
        if row["state_territory"] != "Australia"
    ]

    # 4. Age structure by sex, latest (ABS)
    age_rows = read_csv("abs-age-structure-latest.csv")
    males, females = [], []
    for row in age_rows:
        if row["age_group"].strip().lower() == "all ages":
            continue
        males.append({"x": row["age_group"], "y": int(row["males"])})
        females.append({"x": row["age_group"], "y": int(row["females"])})

    # 5. Total fertility rate, annual (ABS)
    tfr_rows = read_csv("abs-tfr-annual.csv")
    tfr_annual = points(tfr_rows, "year", "tfr")

    # 6. International comparisons (World Bank API / UN WPP)
    fert_rows = read_csv("wb-fertility-comparison.csv")
    fertility_comparison = [
        {"x": row["country_name"], "y": float(row["latest_value"])}
        for row in fert_rows
    ]
    life_rows = read_csv("wb-lifeexpectancy-comparison.csv")
    life_expectancy_comparison = [
        {"x": row["country_name"], "y": float(row["latest_value"])}
        for row in life_rows
    ]

    # Sanity checks — abort rather than emit suspect data.
    assert len(erp_annual) == 45 and erp_annual[0]["x"] == "1981", erp_annual[:1]
    assert abs(erp_annual[-1]["y"] - 27601.7) < 0.01, erp_annual[-1]
    assert len(births) == 180 and births[-1]["x"] == "Mar 2026", births[-1]
    assert abs(nom[-1]["y"] - 101.0) < 0.01, nom[-1]
    assert len(states) == 8, states
    assert len(males) == 21 and len(females) == 21, (len(males), len(females))
    assert len(tfr_annual) == 101 and abs(tfr_annual[-1]["y"] - 1.481) < 0.001
    aus_fert = [p for p in fertility_comparison if p["x"] == "Australia"]
    assert aus_fert and abs(aus_fert[0]["y"] - 1.481) < 0.001
    assert len(fertility_comparison) == 12 and len(life_expectancy_comparison) == 12

    # Build the TS file explicitly for clarity.
    parts = []
    parts.append("/**\n * GENERATED FILE — do not edit by hand.\n")
    parts.append(" * Generated by research/chapter01/scripts/generate-app-data.py\n")
    parts.append(" * from the verified series CSVs in research/chapter01/series/.\n")
    parts.append(" * Full data lineage is documented in the chapter provenance records.\n")
    parts.append(" *\n * Units: ERP and components are in thousands of people (ABS); states and\n")
    parts.append(" * age structure are persons; TFR is babies per woman; comparisons are\n")
    parts.append(" * World Bank API / UN WPP series for 2024.\n */\n")
    parts.append('import type { ChartSeries } from "@/lib/research/types";\n\n')

    def emit(name, comment, data):
        parts.append(f"/** {comment} */\n")
        parts.append(f"export const {name}: ChartSeries[\"data\"] = [\n")
        for point in data:
            parts.append(f'  {{ x: "{point["x"]}", y: {point["y"]} }},\n')
        parts.append("];\n\n")

    emit("erpAnnual", "Estimated Resident Population at 30 June, thousands, Australia, 1981-2025 (ABS).", erp_annual)
    emit("birthsQuarterly", "Births registered, thousands per quarter, Australia, Jun 1981 - Mar 2026 (ABS).", births)
    emit("deathsQuarterly", "Deaths registered, thousands per quarter, Australia, Jun 1981 - Mar 2026 (ABS).", deaths)
    emit("naturalIncreaseQuarterly", "Natural increase (births minus deaths), thousands per quarter, Jun 1981 - Mar 2026 (ABS).", natural_increase)
    emit("netOverseasMigrationQuarterly", "Net overseas migration, thousands per quarter, Jun 1981 - Mar 2026 (ABS).", nom)
    emit("statesLatest", "Population by state and territory, persons, at 31 March 2026 (ABS).", states)
    emit("ageStructureMales", "Males by age group, persons, at 30 June 2025 (ABS).", males)
    emit("ageStructureFemales", "Females by age group, persons, at 30 June 2025 (ABS).", females)
    emit("tfrAnnual", "Total fertility rate, babies per woman, Australia, 1924-2024 (ABS).", tfr_annual)
    emit("fertilityComparison2024", "Total fertility rate, babies per woman, 2024, comparator countries (World Bank API / UN WPP).", fertility_comparison)
    emit("lifeExpectancyComparison2024", "Life expectancy at birth, years, both sexes combined, 2024, comparator countries (World Bank API / UN WPP).", life_expectancy_comparison)

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("".join(parts))

    print(f"Wrote {OUT}")
    print(f"  erpAnnual: {len(erp_annual)} points")
    print(f"  components: {len(births)} quarters x 4 series")
    print(f"  states: {len(states)}")
    print(f"  age structure: {len(males)} age groups x 2 sexes")
    print(f"  tfrAnnual: {len(tfr_annual)} points")
    print(f"  fertilityComparison: {len(fertility_comparison)} countries")
    print(f"  lifeExpectancyComparison: {len(life_expectancy_comparison)} countries")


if __name__ == "__main__":
    main()
